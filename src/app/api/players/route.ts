export async function GET(req: NextRequest) {
  const q = (req.nextUrl.searchParams.get("q") || "").toLowerCase().trim();

  const players = TOP_PLAYERS.map((p, i) => ({
    id: `fp-${i}`,
    name: p.name,
    pos: p.pos,
    team: p.team,
    search: `${p.name} ${p.pos} ${p.team}`.toLowerCase(),
  }));

  if (!q) {
    return NextResponse.json({ players: players.slice(0, 40) });
  }

  const starts = players.filter((p) => p.search.startsWith(q) || p.name.toLowerCase().startsWith(q));
  const includes = players.filter((p) => !starts.includes(p) && p.search.includes(q));

  return NextResponse.json({ players: [...starts, ...includes].slice(0, 50) });
}
